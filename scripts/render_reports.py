def pair_label(data: Mapping[str, Any], pair: str) -> str:
    """'LightGBM frequency x GLM severity' for an expected-loss pair recorded in the results."""
    entry = lookup(data, f"insurance_severity.expected_loss.{pair}")
    if isinstance(entry, Mapping) and present(entry.get("frequency_model")):
        frequency, severity = entry["frequency_model"], entry.get("severity_model")
    elif pair in ("glm", "lgbm"):
        frequency = severity = pair
    else:
        return NOT_MEASURED
    return f"{model_label(frequency)} frequency x {model_label(severity)} severity"


def expected_loss_rows(data: Mapping[str, Any]) -> list[list[str]]:
    """Expected loss = frequency x severity on the test split: GLM pair, LightGBM pair and the served pair."""
    base = "insurance_severity.expected_loss"
    rows = []
    for name in ("glm", "lgbm", "served_pair"):
        label = pair_label(data, name)
        rows.append(
            [
                f"Served by the API: {label}" if name == "served_pair" else label,
                integer(lookup(data, f"{base}.{name}.total_predicted_loss")),
                integer(lookup(data, f"{base}.{name}.total_observed_loss_capped")),
                interval(lookup(data, f"{base}.{name}.observed_to_predicted")),
                interval(lookup(data, f"{base}.{name}.pure_premium_lorenz_gini")),
            ]
        )
    return rows


def served_insurance_versions(data: Mapping[str, Any]) -> list[list[str]]:
    """Which model the API serves for each insurance product, and its version."""
    rows = []
    for target in ("frequency", "severity"):
        section = f"insurance_{target}"
        preferred = lookup(data, f"{section}.preferred_model.name")
        if preferred == "lgbm":
            entry = lookup(data, f"{section}.model_version.{target}_lgbm")
            version = (
                f"{text(entry.get('registered_model'))} v{text(entry.get('version'))} (MLflow registry)"
                if isinstance(entry, Mapping)
                else NOT_MEASURED
            )
        elif preferred == "glm":
            version = (
                f"GLM saved in models/insurance/ (not registered), MLflow run "
                f"`{text(lookup(data, f'{section}.mlflow.run_ids.{target}'))}`"
            )
        else:
            version = NOT_MEASURED
        rows.append(
            [
                target,
                model_label(preferred) if present(preferred) else NOT_MEASURED,
                text(lookup(data, f"{section}.preferred_model.rule")),
                version,
            ]
        )
    return rows


def importance_rows(data: Mapping[str, Any]) -> list[list[str]]:
    """Global SHAP importance of the LightGBM frequency model."""
    ranking = lookup(data, "insurance_frequency.explainability.global_importance")
    if not isinstance(ranking, list) or not ranking:
        return [[NOT_MEASURED, NOT_MEASURED]]
    return [[text(entry.get("feature")), number(entry.get("mean_abs_shap"))] for entry in ranking]


def example_rows(data: Mapping[str, Any]) -> list[list[str]]:
    """Example policies with their top risk-increasing reasons."""
    examples = lookup(data, "insurance_frequency.explainability.examples")
    if not isinstance(examples, list) or not examples:
        return [[NOT_MEASURED] * 3]
    rows = []
    for example in examples:
        reasons = "; ".join(
            f"{reason['reason']} ({reason['feature']} = {reason['value']}, +{number(reason['contribution'], 3)})"
            for reason in example.get("reasons_increase_risk", [])
        )
        rows.append(
            [text(example.get("label")), number(example.get("predicted_frequency_per_year")), reasons or "none"]
        )
    return rows


