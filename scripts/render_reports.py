def _ci_statement(entry: Any, zero_means: str, nonzero_means: str, reference: float = 0.0) -> str:
    """Plain-language reading of whether an interval excludes the reference value."""
    excludes = interval_excludes(entry, reference)
    if excludes is None:
        return NOT_MEASURED
    return nonzero_means if excludes else zero_means


def _fairness_intervals(row: Mapping[str, Any]) -> tuple[dict[str, Any], dict[str, Any]]:
    """(AIR interval, equal-opportunity-difference interval) of one fairness summary row, in bootstrap form."""
    air = {
        "estimate": row.get("adverse_impact_ratio"),
        "ci_low": row.get("air_ci_low"),
        "ci_high": row.get("air_ci_high"),
    }
    eod = {
        "estimate": row.get("equal_opportunity_difference"),
        "ci_low": row.get("eod_ci_low"),
        "ci_high": row.get("eod_ci_high"),
    }
    return air, eod


def fairness_exclusions(data: Mapping[str, Any]) -> tuple[list[dict[str, Any]], int]:
    """Rows whose AIR interval excludes 1 or whose equal-opportunity interval excludes 0, and the number of
    intervals looked at (two per row). Read from fairness_demo.summary_table.fairness."""
    rows = lookup(data, "fairness_demo.summary_table.fairness")
    if not isinstance(rows, list):
        return [], 0
    flagged = []
    for row in rows:
        air, eod = _fairness_intervals(row)
        parts = []
        if interval_excludes(eod, 0.0):
            parts.append(f"equal-opportunity difference {interval(eod, 3)} excludes 0")
        if interval_excludes(air, 1.0):
            parts.append(f"adverse impact ratio {interval(air, 3)} excludes 1")
        if parts:
            flagged.append({"row": row, "text": " and ".join(parts)})
    return flagged, 2 * len(rows)


