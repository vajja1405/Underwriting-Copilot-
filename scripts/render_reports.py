def _code_selection_rule() -> str:
    """The selection rule's threshold from the code, for when the credit section is not measured."""
    return (
        f"LightGBM only if its 2016 validation AUC beats the scorecard by at least {MIN_AUC_GAIN_FOR_LIGHTGBM} and "
        "the lower end of the 95% paired-bootstrap interval of the difference is above 0; otherwise the scorecard."
    )


def _credit_calibration_rows(rows: Any) -> list[list[str]]:
    """Rows of uwcopilot.risk.metrics.calibration_table output."""
    if not isinstance(rows, list) or not rows:
        return [[NOT_MEASURED] * 4]
    return [
        [
            text(row.get("bin")),
            integer(row.get("n_rows")),
            number(row.get("mean_predicted")),
            number(row.get("mean_observed")),
        ]
        for row in rows
    ]


def _credit_psi_summary(data: Mapping[str, Any]) -> str:
    """Flags above the PSI threshold, as recorded."""
    flags = lookup(data, "credit.stability.flags_above_threshold")
    if not isinstance(flags, list):
        reason = section_reason(data, "credit")
        return f"{NOT_MEASURED} ({reason})." if reason else f"{not_measured_text(lookup(data, 'credit.stability'))}."
    if not flags:
        return f"no variable above the threshold ({number(lookup(data, 'credit.stability.threshold'), 2)})."
    shown = "; ".join(f"{flag['variable']} {flag['issue_year']}: {number(flag['psi'], 3)}" for flag in flags)
    return f"flagged above {number(lookup(data, 'credit.stability.threshold'), 2)}: {shown}."


