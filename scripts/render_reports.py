def _ranking_statement(difference: Any) -> str:
    """Which frequency model ranks better, from the paired Lorenz Gini interval (LightGBM minus GLM)."""
    excludes = interval_excludes(difference, 0.0)
    if excludes is None:
        return "the ranking comparison of LightGBM and the GLM is not measured"
    if not excludes:
        return "LightGBM and the GLM rank policies equally well within sampling error"
    if difference["estimate"] > 0:
        return "LightGBM ranks policies better than the GLM"
    return "the GLM ranks policies better than LightGBM"


def _total_calibration_statement(glm: Any, lgbm: Any) -> str:
    """Whether each frequency model is right in total, from the observed / predicted claims intervals."""
    glm_off, lgbm_off = interval_excludes(glm, 1.0), interval_excludes(lgbm, 1.0)
    if glm_off is None or lgbm_off is None:
        return "while total calibration is not measured"
    if not glm_off and not lgbm_off:
        return "while both are calibrated in total"
    if glm_off and lgbm_off:
        return "while neither is calibrated in total (both intervals exclude 1)"
    good = "the GLM" if lgbm_off else "LightGBM"
    return f"while only {good} is calibrated in total (the other interval excludes 1)"


def _severity_vs_frequency(severity: Any, frequency: Any) -> tuple[str, str]:
    """(comparison, consequence) for the severity and frequency Lorenz Ginis of the served models."""
    if interval_excludes(severity, 0.0) is None or interval_excludes(frequency, 0.0) is None:
        return (
            "The severity and frequency rankings are not both measured",
            "so where the pure-premium ranking comes from is not measured",
        )
    if severity["ci_high"] < frequency["ci_low"]:
        return (
            "Severity ranks claims much less sharply than frequency ranks policies",
            "so the pure-premium ranking comes mostly from frequency",
        )
    if severity["ci_low"] > frequency["ci_high"]:
        return (
            "Severity ranks claims more sharply than frequency ranks policies",
            "so severity drives much of the pure-premium ranking",
        )
    return (
        "Severity and frequency rank about equally sharply (their intervals overlap)",
        "so both contribute to the pure-premium ranking",
    )


def _proxy_statement(entry: Any) -> str:
    """The proxy-check clause for age under 25, following its AUC interval (0.5 = no better than chance)."""
    excludes = interval_excludes(entry, 0.5)
    if excludes is None:
        return f"a proxy check (age under 25 from the remaining features: {not_measured_text(entry)})"
    if excludes and entry["ci_low"] > 0.5:
        return (
            "a proxy check showing that dropping protected attributes does not hide them (age under 25 is "
            f"predictable from the remaining features with AUC {interval(entry, 3)})"
        )
    return (
        "a proxy check (age under 25 is not predictable from the remaining features better than chance: AUC "
        f"{interval(entry, 3)})"
    )


