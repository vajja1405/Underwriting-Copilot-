def _observed_entry(row: Mapping[str, Any]) -> dict[str, Any]:
    """The observed-rate interval of one calibration decile, in bootstrap-result form."""
    return {
        "estimate": row.get("mean_observed_rate"),
        "ci_low": row.get("mean_observed_rate_ci_low"),
        "ci_high": row.get("mean_observed_rate_ci_high"),
    }


def _decile_outside_ci(row: Mapping[str, Any]) -> bool:
    """True if the decile's mean prediction lies outside its observed-rate interval."""
    predicted = row.get("mean_predicted_rate")
    return is_number(predicted) and interval_excludes(_observed_entry(row), predicted) is True


def _proxy_interval(row: Mapping[str, Any]) -> str:
    """Proxy-check AUC with its interval, from a summary-table row."""
    entry = {
        "estimate": row.get("proxy_auc"),
        "ci_low": row.get("proxy_auc_ci_low"),
        "ci_high": row.get("proxy_auc_ci_high"),
    }
    return interval(entry, 3)


