def lookup(data: Mapping[str, Any], path: str) -> Any:
    """Value at a dotted path, or None if any part is missing.

    "insurance_frequency.test_metrics.glm" is read as data["insurance_frequency"]["results"]["test_metrics"]
    ["glm"]: "results" is implied after a section name unless the path says "metadata". List items are
    addressed by number ("examples.0.IDpol").
    """
    keys = path.split(".")
    if len(keys) > 1 and keys[0] in SECTIONS and keys[1] not in ("results", "metadata"):
        keys.insert(1, "results")
    value: Any = data
    for key in keys:
        if isinstance(value, Mapping) and key in value:
            value = value[key]
        elif isinstance(value, list) and key.isdigit() and int(key) < len(value):
            value = value[int(key)]
        else:
            return None
    return value


def present(value: Any) -> bool:
    """True if value is a real result: not missing, not a "not measured" record, not NaN or infinite."""
    if value is None or is_not_measured(value):
        return False
    if isinstance(value, float) and not math.isfinite(value):
        return False
    return True


def is_number(value: Any) -> bool:
    """A JSON number (bool is not a number here)."""
    return isinstance(value, int | float) and not isinstance(value, bool) and present(value)


def section_reason(data: Mapping[str, Any], section: str) -> str | None:
    """The recorded reason if a whole section is "not measured", else None."""
    results = lookup(data, f"{section}.results")
    if results is None:
        return "no results recorded"
    if is_not_measured(results):
        return str(results.get("reason", "no reason recorded"))
    return None


def section_measured(data: Mapping[str, Any], section: str) -> bool:
    """True if the section exists and is not marked "not measured"."""
    return section_reason(data, section) is None


