def _grouped_split_bullet(data: Mapping[str, Any]) -> str:
    """Executive-summary bullet for the identical-risks sensitivity check (wording follows the intervals)."""
    grouped = "insurance_frequency.grouped_split_sensitivity"
    difference = lookup(data, f"{grouped}.lgbm_minus_glm.mean_poisson_deviance")
    headline = lookup(data, "insurance_frequency.test_metrics.lgbm_minus_glm.mean_poisson_deviance")
    if interval_excludes(difference, 0.0) is None:
        return f"Identical risks in train and test: {not_measured_text(lookup(data, grouped))}."
    same_sign = (
        interval_excludes(headline, 0.0)
        and interval_excludes(difference, 0.0)
        and (difference["estimate"] > 0) == (headline["estimate"] > 0)
    )
    shared = lookup(data, f"{grouped}.{SHARED_RATING_VECTOR}.random_split")
    return (
        f"Identical risks in train and test: {percent(shared)} "
        "of test policies share every rating feature with a training policy. On a split grouped on the rating "
        f"features, LightGBM minus GLM mean Poisson deviance is {interval(difference)} (headline random split "
        f"{interval(headline)}); "
        + (
            "the conclusion does not depend on how identical risks are split."
            if same_sign
            else "the comparison is sensitive to how identical risks are split."
        )
    )


