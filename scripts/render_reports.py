def template_context(data: Mapping[str, Any]) -> dict[str, Any]:
    """The results JSON plus the derived statements, as the walkthrough template sees them."""
    return {**data, "derived": walkthrough_statements(data)}


PLACEHOLDER = re.compile(r"\{\{\s*([A-Za-z0-9_.]+)\s*(?:\|\s*([a-z0-9]+)\s*)?\}\}")
TEMPLATE_ONLY = re.compile(r"<!-- template-only:.*?-->\n?", re.DOTALL)
FORMATS: dict[str, Callable[[Any], str]] = {
    "ci": interval,
    "ci3": lambda value: interval(value, 3),
    "f2": lambda value: number(value, 2),
    "f3": lambda value: number(value, 3),
    "f4": number,
    "int": integer,
    "amount": amount,
    "pct": percent,
    "pct2": lambda value: percent(value, 2),
    "sci": scientific,
    "text": text,
    "model": model_label,
}


def render_template(template: str, data: Mapping[str, Any]) -> str:
    """Replace every {{ path | format }} with the formatted JSON value ('not measured' if missing).

    Paths starting with "derived." read walkthrough_statements(data): sentences whose wording follows the
    intervals. A leading <!-- template-only: ... --> comment (notes for editors of the template) is removed.

    Formats: ci (estimate [low, high], 4 decimals), ci3, f2, f3, f4, int, amount, pct, pct2, sci, text, model.
    Without a format, numbers get 4 decimals and anything else is shown as text.
    """

    context = template_context(data)

    def replace(match: re.Match[str]) -> str:
        path, kind = match.group(1), match.group(2)
        value = lookup(context, path)
        if kind is None:
            return number(value) if is_number(value) and isinstance(value, float) else text(value)
        if kind not in FORMATS:
            raise ValueError(f"unknown format '{kind}' in placeholder {match.group(0)}")
        return FORMATS[kind](value)

    return PLACEHOLDER.sub(replace, TEMPLATE_ONLY.sub("", template))


def placeholder_paths(template: str) -> list[str]:
    """Every JSON path the template refers to (used by the tests to catch typos)."""
    return [match.group(1) for match in PLACEHOLDER.finditer(TEMPLATE_ONLY.sub("", template))]


