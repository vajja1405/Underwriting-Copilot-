import type { NextConfig } from "next";
import { PHASE_DEVELOPMENT_SERVER } from "next/constants";

/**
 * Fundproof frontend build configuration.
 *
 * `next build` (production): a fully static export written to `out/`, served by the FastAPI app
 * (`uwcopilot.web.app`). `trailingSlash: true` writes every page as `<route>/index.html`
 * (for example `out/studio/index.html`), so any plain static file server can serve it:
 * FastAPI, `python -m http.server`, or the Docker image. Links render as `/studio/`.
 *
 * `next dev` (development): no static export, and `/api/*` is proxied to the FastAPI dev server
 * (UWC_API_DEV_ORIGIN, default http://127.0.0.1:8000) so the browser still talks to ONE origin and the
 * session cookie and CSRF double-submit work exactly as in production. Trailing slashes are off in dev
 * so `/api/me` is not redirected to `/api/me/` before the proxy sees it.
 */
const API_DEV_ORIGIN = process.env.UWC_API_DEV_ORIGIN ?? "http://127.0.0.1:8000";

const sharedConfig: NextConfig = {
  reactStrictMode: true,
  poweredByHeader: false,
  // The static export has no image optimization server.
  images: { unoptimized: true },
  // `next dev` would otherwise write AGENTS.md and CLAUDE.md into frontend/ when it detects a coding agent.
  // Agent instructions in this repo are owned by the project owners (root CLAUDE.md), not generated by tools.
  agentRules: false,
};

export default function nextConfig(phase: string): NextConfig {
  if (phase === PHASE_DEVELOPMENT_SERVER) {
    return {
      ...sharedConfig,
      trailingSlash: false,
      async rewrites() {
        return [{ source: "/api/:path*", destination: `${API_DEV_ORIGIN}/api/:path*` }];
      },
    };
  }
  return {
    ...sharedConfig,
    output: "export",
    trailingSlash: true,
  };
}
