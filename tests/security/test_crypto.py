def test_encrypted_log_round_trip_and_no_plaintext_on_disk(tmp_path: Path) -> None:
    path = tmp_path / "records.jsonl"
    log = EncryptedDecisionLog(path, new_encryptor())
    stored = log.append(record("DR-aaa", memo={"summary": "Revenue of $412,000.00"}))
    assert stored["legal_name"] == SYNTHETIC_NAME and stored["record_sha256"]
    log.append(record("DR-bbb"))
    assert [item["record_id"] for item in log.records()] == ["DR-aaa", "DR-bbb"]
    assert log.find("DR-bbb")["legal_name"] == SYNTHETIC_NAME and log.find("DR-zzz") is None
    text = path.read_text(encoding="utf-8")
    for secret in (SYNTHETIC_NAME, "Northwind", "APP-C-901", "412,000"):
        assert secret not in text
    assert set(json.loads(text.splitlines()[0])) == {
        "record_id",
        "payload_encryption",
        "payload",
        "schema_version",
        "previous_record_sha256",
        "record_sha256",
    }


def test_encrypted_log_chain_is_verifiable_without_the_key(tmp_path: Path) -> None:
    path = tmp_path / "records.jsonl"
    log = EncryptedDecisionLog(path, new_encryptor())
    for index in range(3):
        log.append(record(f"DR-{index}"))
    assert log.verify_chain() == [] and log.verify_payloads() == []
    assert DecisionLog(path).verify_chain() == []  # plain DecisionLog, no key at all
    stranger = EncryptedDecisionLog(path, new_encryptor())  # wrong key
    assert stranger.verify_chain() == []
    with pytest.raises(CryptoError):
        stranger.records()
    assert len(stranger.verify_payloads()) == 3


def test_encrypted_log_append_is_idempotent_by_record_id(tmp_path: Path) -> None:
    log = EncryptedDecisionLog(tmp_path / "records.jsonl", new_encryptor())
    first = log.append(record("DR-same", n=1))
    again = log.append(record("DR-same", n=2))
    assert again == first and len(log.envelopes()) == 1 and log.records()[0]["n"] == 1


def test_encrypted_log_detects_an_edited_ciphertext(tmp_path: Path) -> None:
    path = tmp_path / "records.jsonl"
    log = EncryptedDecisionLog(path, new_encryptor())
    log.append(record("DR-1"))
    log.append(record("DR-2"))
    lines = path.read_text(encoding="utf-8").splitlines()
    envelope = json.loads(lines[0])
    envelope["payload"] = envelope["payload"][:-6] + ("A" if envelope["payload"][-6] != "A" else "B") + "AAAAA"
    path.write_text("\n".join([json.dumps(envelope), lines[1]]) + "\n", encoding="utf-8")
    assert any("record_sha256 does not match" in problem for problem in log.verify_chain())
    assert any(problem.startswith("record 0:") for problem in log.verify_payloads())


def test_encrypted_log_detects_payloads_swapped_between_lines(tmp_path: Path) -> None:
    """Even a re-chained file (all hashes recomputed) cannot move a payload to another record id."""
    path = tmp_path / "records.jsonl"
    log = EncryptedDecisionLog(path, new_encryptor())
    log.append(record("DR-1"))
    log.append(record("DR-2"))
    first, second = (json.loads(line) for line in path.read_text(encoding="utf-8").splitlines())
    first["payload"], second["payload"] = second["payload"], first["payload"]
    first["record_sha256"] = record_hash(first)
    second["previous_record_sha256"] = first["record_sha256"]
    second["record_sha256"] = record_hash(second)
    path.write_text(json.dumps(first) + "\n" + json.dumps(second) + "\n", encoding="utf-8")
    assert log.verify_chain() == []  # the forger re-chained it
    problems = log.verify_payloads()
    assert len(problems) == 2 and all("belongs to another record" in problem for problem in problems)


def test_encrypted_log_refuses_a_file_with_plaintext_records(tmp_path: Path) -> None:
    path = tmp_path / "records.jsonl"
    DecisionLog(path).append(record("DR-plain"))
    log = EncryptedDecisionLog(path, new_encryptor())
    with pytest.raises(CryptoError, match="plaintext record"):
        log.append(record("DR-enc"))
    assert len(DecisionLog(path).records()) == 1  # nothing was appended


def test_encrypted_log_is_a_drop_in_for_the_evidence_records(tmp_path: Path) -> None:
    log = EncryptedDecisionLog(tmp_path / "records.jsonl", new_encryptor())
    stored = append_record(record("EV-0123456789abcdef01234567"), log)
    assert stored["record_id"] == "EV-0123456789abcdef01234567" and log.verify_chain() == []


def test_agent_writes_its_decision_record_encrypted(tmp_path: Path) -> None:
    application = committed_by_scenario("clean_term_dental")
    deps = make_deps(tmp_path)
    path = tmp_path / "encrypted_records.jsonl"
    encryptor = new_encryptor()
    deps.decision_log = EncryptedDecisionLog(path, encryptor)
    agent = memory_agent(deps)
    start_run(agent, application.model_dump(mode="json"), "t-enc")
    done = resume_run(agent, "t-enc", UW_REFER)
    assert done.state["status"] == "referred_by_human"
    [stored] = EncryptedDecisionLog(path, encryptor).records()
    assert stored["application_id"] == application.application_id
    assert stored["record_sha256"] == done.state["decision_record"]["record_sha256"]
    assert application.applicant.legal_name not in path.read_text(encoding="utf-8")
    assert DecisionLog(path).verify_chain() == []


