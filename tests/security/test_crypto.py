def test_security_crypto_re_exports_the_web_encryptor() -> None:
    assert security_crypto.Encryptor is web_crypto.Encryptor
    assert security_crypto.CryptoError is web_crypto.CryptoError
    assert security_crypto.parse_fernet_keys is web_crypto.parse_fernet_keys


def test_encryptor_from_env_needs_a_key() -> None:
    with pytest.raises(CryptoError, match="UWC_FERNET_KEY is not set"):
        encryptor_from_env(env_file=None, environ={})
    with pytest.raises(CryptoError, match="not a valid Fernet key"):
        encryptor_from_env(env_file=None, environ={"UWC_FERNET_KEY": "not-a-key"})


def test_encryptor_from_env_round_trip_and_rotation(tmp_path: Path) -> None:
    old_key, new_key = generate_key(), generate_key()
    old = encryptor_from_env(env_file=None, environ={"UWC_FERNET_KEY": old_key})
    token = old.encrypt(b"SYNTHETIC")
    env_file = tmp_path / ".env"
    env_file.write_text(f"UWC_FERNET_KEY={new_key},{old_key}\n", encoding="utf-8")
    rotated = encryptor_from_env(env_file=env_file, environ={"UWC_FERNET_KEY": "ignored-the-env-file-wins"})
    assert rotated.decrypt(token) == b"SYNTHETIC"  # the old key still decrypts
    with pytest.raises(CryptoError):
        old.decrypt(rotated.encrypt(b"x"))  # the new key encrypts


