SYNTHETIC_NAME = "Northwind Imaginary Bakery LLC"  # SYNTHETIC
PDF = b"%PDF-1.4\n% SYNTHETIC test packet\n" + SYNTHETIC_NAME.encode() + b"\n%%EOF\n"
UW_REFER = {
    "action": "refer",
    "reviewer_id": "uw.one",
    "role": "underwriter",
    "rationale": "Refer for a second look at the file.",
}


def new_encryptor() -> Encryptor:
    """An encryptor with a fresh random key."""
    return Encryptor([generate_key().encode("ascii")])


def record(record_id: str, **fields: object) -> dict:
    """A small SYNTHETIC decision record."""
    return {"record_id": record_id, "application_id": "APP-C-901", "legal_name": SYNTHETIC_NAME, **fields}


