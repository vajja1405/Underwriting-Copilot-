def test_packet_store_round_trip_and_ciphertext_on_disk(tmp_path: Path) -> None:
    store = EncryptedPacketStore(tmp_path / "packets", new_encryptor())
    meta = store.put("PKT-C-901", PDF)
    assert meta.size_bytes == len(PDF) and store.has("PKT-C-901") and store.packet_ids() == ["PKT-C-901"]
    assert store.get("PKT-C-901") == PDF
    on_disk = (tmp_path / "packets" / "PKT-C-901" / "packet.pdf.enc").read_bytes()
    assert b"%PDF" not in on_disk and SYNTHETIC_NAME.encode() not in on_disk
    mode = stat.S_IMODE((tmp_path / "packets" / "PKT-C-901" / "packet.pdf.enc").stat().st_mode)
    assert mode == 0o600
    assert store.meta("PKT-C-901").sha256 == meta.sha256  # readable without the key


def test_packet_store_refuses_bad_input(tmp_path: Path) -> None:
    store = EncryptedPacketStore(tmp_path / "packets", new_encryptor())
    with pytest.raises(PacketStoreError, match="only PDF"):
        store.put("PKT-C-902", b"MZ not a pdf")
    store.put("PKT-C-902", PDF)
    with pytest.raises(PacketStoreError, match="never overwritten"):
        store.put("PKT-C-902", PDF)
    for bad_id in ("../escape", "a/b", "..", ".hidden", "", "x" * 65):
        with pytest.raises(PacketStoreError, match="packet id"):
            store.put(bad_id, PDF)
    with pytest.raises(PacketStoreError, match="not stored"):
        store.get("PKT-C-404")


def test_packet_store_refuses_a_file_copied_from_another_packet(tmp_path: Path) -> None:
    store = EncryptedPacketStore(tmp_path / "packets", new_encryptor())
    store.put("PKT-C-001", PDF)
    store.put("PKT-C-002", PDF.replace(b"SYNTHETIC", b"OTHER-SYNTHETIC"))
    root = tmp_path / "packets"
    (root / "PKT-C-002" / "packet.pdf.enc").write_bytes((root / "PKT-C-001" / "packet.pdf.enc").read_bytes())
    with pytest.raises(PacketStoreError, match="belongs to another packet"):
        store.get("PKT-C-002")


def test_packet_store_checks_the_recorded_sha256_and_the_key(tmp_path: Path) -> None:
    store = EncryptedPacketStore(tmp_path / "packets", new_encryptor())
    store.put("PKT-C-003", PDF)
    meta_path = tmp_path / "packets" / "PKT-C-003" / "packet.meta.json"
    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    meta_path.write_text(json.dumps({**meta, "sha256": "0" * 64}), encoding="utf-8")
    with pytest.raises(PacketStoreError, match="SHA-256"):
        store.get("PKT-C-003")
    with pytest.raises(CryptoError):
        EncryptedPacketStore(tmp_path / "packets", new_encryptor()).get("PKT-C-003")


def test_decrypted_file_is_private_and_removed_afterwards(tmp_path: Path) -> None:
    store = EncryptedPacketStore(tmp_path / "packets", new_encryptor())
    store.put("PKT-I-001", PDF)
    scratch = tmp_path / "scratch"
    scratch.mkdir()
    with store.decrypted_file("PKT-I-001", temp_dir=scratch) as pdf_path:
        assert pdf_path.read_bytes() == PDF
        assert stat.S_IMODE(pdf_path.stat().st_mode) == 0o600
        assert stat.S_IMODE(pdf_path.parent.stat().st_mode) == 0o700
    assert not pdf_path.exists() and list(scratch.iterdir()) == []


def test_packet_store_delete(tmp_path: Path) -> None:
    store = EncryptedPacketStore(tmp_path / "packets", new_encryptor())
    store.put("PKT-C-004", PDF)
    assert store.delete("PKT-C-004") is True and not store.has("PKT-C-004")
    assert store.delete("PKT-C-004") is False and store.packet_ids() == []


def test_security_settings_defaults_and_overrides(tmp_path: Path) -> None:
    defaults = load_security_settings(env_file=None, environ={})
    assert defaults.audit_log == DEFAULT_AUDIT_LOG and defaults.packet_store == DEFAULT_PACKET_STORE
    custom = load_security_settings(
        env_file=None, environ={"UWC_AUDIT_LOG": str(tmp_path / "a.jsonl"), "UWC_PACKET_STORE": str(tmp_path / "p")}
    )
    assert custom.audit_log == tmp_path / "a.jsonl" and custom.packet_store == tmp_path / "p"
